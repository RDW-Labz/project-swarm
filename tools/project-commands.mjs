// The project-level commands that let any agent take over: brief, handoff, checkpoint, and the
// automatic journal. The runner calls these; no model is involved.
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { appendEvent, readJournal, sanitizeText, safeWritableDir, assertRegularOrMissing } from './journal.mjs';
import { readLedger, ledgerStats } from './tickets.mjs';
import { loadRuns, buildBrief, renderBrief, renderHandoff, renderAgentHandoff } from './brief.mjs';

const HANDOFF_MARKER = '<!-- generated by swarm; do not edit';
const MAX_CHECKPOINTS = 20;

// Commands that never touch a project's journal: they act on the install or print static text.
export const NO_JOURNAL = Object.freeze(['version', 'update', 'completion', '__complete', 'help', '--help', '-h', 'lesson', 'scale', 'onboard', 'checkpoint']);
// Commands that act on the install itself, so they keep the install root even from a project directory.
export const INSTALL_COMMANDS = Object.freeze(['version', 'update', 'onboard']);

// The nearest folder at or above `cwd` that is a swarm project or a git work tree; `cwd` itself otherwise.
export function findProjectRoot(cwd) {
  let dir = path.resolve(cwd);
  for (;;) {
    if (existsSync(path.join(dir, '.project-swarm.json')) || existsSync(path.join(dir, '.git'))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}
export function projectRootFrom(cwd) {
  return findProjectRoot(cwd) ?? path.resolve(cwd);
}

// Run from the shared install (`.../versions/<x>/tools/swarm.mjs`), the default root is the project the
// operator is standing in (nearest swarm project or git root), initialized or not. Only outside any git
// repo does it fall back to the install. Run from a checkout, it stays that checkout.
export function resolveDefaultRoot(ownRoot, cwd) {
  return path.basename(path.dirname(ownRoot)) === 'versions' ? (findProjectRoot(cwd) ?? ownRoot) : ownRoot;
}

export function isSwarmProject(root) {
  return existsSync(path.join(root, '.project-swarm.json')) || existsSync(path.join(root, '.swarm'));
}

const trim = (value, length = 160) => (value.length > length ? `${value.slice(0, length)}…` : value);

const SECRET_FLAG = /^--?[\w-]*(?:key|token|secret|password|passwd|auth|credential)[\w-]*$/i;

// `--root X` is not part of what the operator asked for. Everything else is kept with secrets redacted,
// including the value that follows a secret-looking flag (`--token VALUE`, `--api-key=VALUE`).
export function journalCommandEvent(argv, status, ms) {
  const rest = [];
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--root') { index += 1; continue; }
    rest.push(String(argv[index]));
  }
  const [cmd = '', ...raw] = rest;
  const args = [];
  for (let index = 0; index < raw.length; index += 1) {
    const arg = raw[index];
    const equals = arg.indexOf('=');
    if (arg.startsWith('-') && equals > 0 && SECRET_FLAG.test(arg.slice(0, equals))) { args.push(`${arg.slice(0, equals)}=[redacted]`); continue; }
    args.push(arg);
    if (SECRET_FLAG.test(arg) && index + 1 < raw.length) { args.push('[redacted]'); index += 1; }
  }
  return { kind: 'command', cmd: trim(sanitizeText(cmd), 60), args: args.slice(0, 12).map(arg => trim(sanitizeText(arg))), status, ms };
}

// The operator's argument for a command: the first token that is not a flag and not a bare number, so
// `go --max-usd 5 "goal"` yields the goal, not "5".
export function pickArgument(rest) {
  return rest.find(arg => !arg.startsWith('--') && !/^-?\d+(\.\d+)?$/.test(arg));
}

const sumCost = jobs => {
  const costs = (jobs ?? []).map(job => job?.costUsd).filter(value => typeof value === 'number' && Number.isFinite(value));
  return costs.length ? costs.reduce((a, b) => a + b, 0) : undefined;
};

// Structured journal events from a command's printed result, so the brief can say what is done.
export function eventsFromResult(command, argument, result) {
  if (!result || typeof result !== 'object') return [];
  const out = [];
  if (command === 'run' && typeof result.id === 'string' && typeof result.status === 'string') {
    const cost = sumCost(result.jobs);
    out.push({ kind: 'run', id: result.id, status: result.status, ...(result.summary?.counts ? { counts: result.summary.counts } : {}), ...(cost !== undefined ? { costUsd: cost } : {}), ...(typeof argument === 'string' ? { manifest: argument } : {}) });
  }
  if (command === 'integrate') {
    if (typeof result.id === 'string' && result.status === 'integrated') out.push({ kind: 'integration', run: result.id, status: 'complete', ...(Array.isArray(result.files) ? { files: result.files.length } : {}) });
    else if (Array.isArray(result.integrated)) for (const entry of result.integrated) if (entry?.run) out.push({ kind: 'integration', run: entry.run, status: 'complete' });
  }
  if (command === 'ship') {
    const url = result.prUrl ?? result.pr?.url ?? result.url;
    if (typeof url === 'string' || result.status) out.push({ kind: 'pr', ...(typeof url === 'string' ? { url } : {}), status: result.merged === true ? 'merged' : result.merged === false ? 'opened' : result.status === 'complete' ? 'merged' : 'opened' });
  }
  if (command === 'go' && typeof argument === 'string' && result.status) {
    out.push({ kind: 'goal', text: argument });
    if (typeof result.runId === 'string') out.push({ kind: 'run', id: result.runId, status: result.status === 'complete' ? 'complete' : result.status });
  }
  return out;
}

async function readText(file) {
  try { return await fs.readFile(file, 'utf8'); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function currentBrief(root, { now = Date.now } = {}) {
  const [events, runs] = await Promise.all([readJournal(root), loadRuns(root)]);
  const brief = buildBrief({ root, events, runs, now });
  const ledger = await readLedger(root).catch(() => null);
  if (ledger) {
    const s = ledgerStats(ledger);
    brief.tickets = { total: s.total, percentDone: s.percentDone, byStatus: s.byStatus };
  }
  return brief;
}

// Regenerates coordination/HANDOFF.md from the journal. Only in a project that has a coordination folder.
// A hand-written file is kept once as HANDOFF.previous.md, never lost; an unchanged result is not rewritten.
// A file is ours to replace only if it is empty, was generated by swarm, or is the untouched template.
const TEMPLATE_START = '# Handoff\n\nStatus: not started.';
const isReplaceable = before => !before.trim() || before.startsWith(HANDOFF_MARKER) || (before.startsWith(TEMPLATE_START) && before.length < 1500);

export async function writeHandoffFile(root, { now = Date.now } = {}) {
  if (!existsSync(path.join(root, 'coordination'))) return { written: false, reason: 'no coordination folder' };
  const dir = await safeWritableDir(root, ['coordination']);
  const target = path.join(dir, 'HANDOFF.md');
  await assertRegularOrMissing(target);
  const next = renderHandoff(await currentBrief(root, { now }));
  const before = await readText(target);
  if (before === next) return { written: false, reason: 'unchanged' };
  if (before !== null && !isReplaceable(before)) {
    // Hand-written content is never lost: it is kept under a name that does not exist yet.
    let backup = path.join(dir, 'HANDOFF.previous.md');
    for (let n = 2; existsSync(backup); n += 1) backup = path.join(dir, `HANDOFF.previous-${n}.md`);
    await fs.writeFile(backup, before, { flag: 'wx' });
  }
  const handle = await fs.open(target, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_TRUNC | fs.constants.O_NOFOLLOW, 0o644);
  try { await handle.writeFile(next); } finally { await handle.close(); }
  return { written: true };
}

export async function runBriefCommand(root, args, { now = Date.now } = {}) {
  if (args.some(arg => arg !== '--json')) return { stdout: 'Usage: swarm brief [--json]\n', exitCode: 1 };
  const brief = await currentBrief(root, { now });
  return { stdout: args.includes('--json') ? `${JSON.stringify(brief)}\n` : `${renderBrief(brief)}\n`, exitCode: 0 };
}

export async function runHandoffCommand(root, args, { now = Date.now } = {}) {
  if (['generate', 'check', 'status', 'final'].includes(args[0])) return (await import('./handoff-commands.mjs')).runHandoffDocs(root, args);
  const at = args.indexOf('--to');
  if (args.length !== 2 || at !== 0 || !args[1]) return { stdout: 'Usage: swarm handoff --to codex|cursor|claude|gemini | generate --stage S3 | check --url URL | status | final\n', exitCode: 1 };
  const brief = await currentBrief(root, { now });
  try { return { stdout: `${renderAgentHandoff(brief, args[1])}\n`, exitCode: 0 }; }
  catch (error) { return { stdout: `${error.message}\nUsage: swarm handoff --to codex|cursor|claude|gemini\n`, exitCode: 1 }; }
}

// Snapshots the brief into .swarm/project/checkpoints (the newest 20 kept), journals it, and refreshes HANDOFF.md.
export async function runCheckpointCommand(root, args, { now = Date.now } = {}) {
  if (args.some(arg => arg !== '--quiet')) return { stdout: 'Usage: swarm checkpoint [--quiet]\n', exitCode: 1 };
  const brief = await currentBrief(root, { now });
  const dir = await safeWritableDir(root, ['.swarm', 'project', 'checkpoints']);
  const name = `${new Date(now()).toISOString().replace(/[:.]/g, '-')}.md`;
  await fs.writeFile(path.join(dir, name), `${renderBrief(brief)}\n`);
  // Only regular .md files inside the checkpoints folder are ever removed.
  const entries = (await fs.readdir(dir, { withFileTypes: true })).filter(entry => entry.isFile() && entry.name.endsWith('.md')).map(entry => entry.name).sort();
  for (const old of entries.slice(0, Math.max(0, entries.length - MAX_CHECKPOINTS))) await fs.rm(path.join(dir, old), { force: true });
  await appendEvent(root, { kind: 'checkpoint', file: `.swarm/project/checkpoints/${name}` }, { now, best: true });
  await writeHandoffFile(root, { now });
  return { stdout: args.includes('--quiet') ? '' : `checkpoint saved: .swarm/project/checkpoints/${name}\n`, exitCode: 0 };
}

// Called once at the end of every command (see main()).
export async function journalAfterCommand(root, argv, { status, ms, printed, now = Date.now } = {}) {
  const command = argv.filter((arg, index) => !(arg === '--root' || argv[index - 1] === '--root'))[0] ?? '';
  // `swarm init --check` promises to write nothing, so it leaves no journal line either.
  if (!command || NO_JOURNAL.includes(command) || !isSwarmProject(root) || (command === 'init' && argv.includes('--check'))) return;
  await appendEvent(root, journalCommandEvent(argv, status, ms), { now, best: true });
  const rest = argv.filter((arg, index) => !(arg === '--root' || argv[index - 1] === '--root')).slice(1);
  const argument = pickArgument(rest);
  if (command === 'note' && rest.length && status === 'ok') await appendEvent(root, { kind: 'note', text: rest[rest.length - 1] }, { now, best: true });
  // Results become run, integration or PR events only from a command that succeeded: text printed by a
  // failed command, or echoed from a worker, must not be able to forge "integration complete".
  let result = null;
  if (printed && status === 'ok') { try { result = JSON.parse(printed.trim().split('\n').at(-1)); } catch { result = null; } }
  for (const event of eventsFromResult(command, argument, result)) await appendEvent(root, event, { now, best: true });
  await writeHandoffFile(root, { now }).catch(() => {});
}
