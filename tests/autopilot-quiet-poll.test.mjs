import './_isolate-config.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { runAutopilot } from '../tools/autopilot.mjs';
import { appendEvent, readJournal } from '../tools/journal.mjs';
import { loadRuns } from '../tools/brief.mjs';

const execFileAsync = promisify(execFile);
const NOW = Date.parse('2030-07-01T12:00:00.000Z');
const swarmEntry = path.join(path.dirname(fileURLToPath(import.meta.url)), '../tools/swarm.mjs');
const tmpBase = () => process.env.SWARM_TEST_TMP || os.tmpdir();

async function project(t) {
  const root = await fs.realpath(await fs.mkdtemp(path.join(tmpBase(), 'autopilot-quiet-')));
  const home = await fs.mkdtemp(path.join(tmpBase(), 'autopilot-quiet-home-'));
  const env = {
    HOME: home,
    GIT_CONFIG_GLOBAL: path.join(home, '.gitconfig'),
    GIT_CONFIG_SYSTEM: '/dev/null',
    SWARM_CONFIG: process.env.SWARM_CONFIG,
    SWARM_TEST_TMP: process.env.SWARM_TEST_TMP,
    PATH: process.env.PATH,
  };
  t.after(async () => {
    await fs.rm(root, { recursive: true, force: true }).catch(() => {});
    await fs.rm(home, { recursive: true, force: true }).catch(() => {});
  });
  await fs.writeFile(path.join(root, '.project-swarm.json'), JSON.stringify({ install: '/x', version: '1.0.0' }));
  await fs.mkdir(path.join(root, '.swarm', 'project'), { recursive: true });
  await fs.mkdir(path.join(root, 'coordination'), { recursive: true });
  await fs.writeFile(path.join(root, 'coordination/TASK.md'), '# Task\n');
  await fs.writeFile(path.join(root, 'coordination/HANDOFF.md'), '<!-- generated by swarm; do not edit -->\n\n# Project Swarm handoff\n');
  await appendEvent(root, { kind: 'goal', text: 'quiet poll fixture', doneWhen: 'stable' }, { now: () => NOW });
  await execFileAsync('git', ['init', '-q'], { cwd: root, env });
  await execFileAsync('git', ['-c', 'user.name=T', '-c', 'user.email=t@example.invalid', 'add', '-A'], { cwd: root, env });
  await execFileAsync('git', ['-c', 'user.name=T', '-c', 'user.email=t@example.invalid', 'commit', '-qm', 'init'], { cwd: root, env });
  return { root, env };
}

async function snapshotTree(root) {
  const out = new Map();
  async function walk(rel) {
    const abs = path.join(root, rel);
    let entries;
    try { entries = await fs.readdir(abs, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      const child = rel ? `${rel}/${entry.name}` : entry.name;
      if (child === '.swarm' || child.startsWith('.swarm/')) {
        if (entry.isDirectory()) await walk(child);
        continue;
      }
      if (entry.isDirectory()) await walk(child);
      else {
        const full = path.join(root, child);
        const stat = await fs.stat(full);
        const bytes = await fs.readFile(full);
        out.set(child, { mtimeMs: stat.mtimeMs, bytes });
      }
    }
  }
  await walk('');
  return out;
}

function minimalAutopilotDeps(root) {
  return {
    loadRuns: () => loadRuns(root),
    readJournal: () => readJournal(root, { limit: Infinity }),
    appendEvent: (r, event) => appendEvent(r, event, { now: () => NOW, best: true }),
    readPlan: async () => null,
    checkout: async () => ({ branch: 'swarm/work', dirty: false }),
    integrate: async () => ({}),
    resume: async () => {},
    retryFailed: async () => ({}),
  };
}

test('two quiet autopilot --once polls write no project files outside run locks', async t => {
  const { root, env } = await project(t);
  const before = await snapshotTree(root);
  const journalBefore = (await readJournal(root, { limit: Infinity })).length;
  await execFileAsync(process.execPath, [swarmEntry, '--root', root, 'autopilot', '--once'], { env, maxBuffer: 8 * 1024 * 1024 });
  await execFileAsync(process.execPath, [swarmEntry, '--root', root, 'autopilot', '--once'], { env, maxBuffer: 8 * 1024 * 1024 });
  const after = await snapshotTree(root);
  const journalAfter = (await readJournal(root, { limit: Infinity })).length;
  assert.equal(journalAfter, journalBefore, 'quiet autopilot polls must not append journal lines');
  for (const [rel, snap] of before) {
    const later = after.get(rel);
    assert.ok(later, `missing ${rel}`);
    assert.equal(later.mtimeMs, snap.mtimeMs, `mtime changed: ${rel}`);
    assert.deepEqual(later.bytes, snap.bytes, `bytes changed: ${rel}`);
  }
  assert.equal(after.size, before.size);
});

test('runAutopilot once with idle deps sets stepWroteJournal false', async t => {
  const { root } = await project(t);
  const [step] = await runAutopilot(root, minimalAutopilotDeps(root), { once: true, now: () => NOW, sleep: async () => {} });
  assert.equal(step.idle, true);
  assert.equal(step.stepWroteJournal, false);
});
