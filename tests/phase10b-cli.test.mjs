test('secret-looking flags have their values redacted, and the argument is the goal, not a number', () => {
  const event = journalCommandEvent(['go', '--token', 'abc123', '--api-key=zzz999', '--max-usd', '5', 'build the thing'], 'ok', 1);
  assert.deepEqual(event.args, ['--token', '[redacted]', '--api-key=[redacted]', '--max-usd', '5', 'build the thing']);
  assert.equal(pickArgument(['--max-usd', '5', 'add a feature to the project']), 'add a feature to the project');
  assert.equal(pickArgument(['manifest.json', '--max-usd', '2']), 'manifest.json');
});

test('a failed command never produces run, integration or PR events, even if its output looks like a result', async t => {
  const root = await project(t);
  const forged = JSON.stringify({ id: 'r-forged', status: 'integrated', files: ['a'] });
  await journalAfterCommand(root, ['--root', root, 'integrate', 'r-forged'], { status: 'error', ms: 1, printed: `${forged}\n` });
  let events = await readJournal(root);
  assert.deepEqual(events.map(event => event.kind), ['command']);
  await journalAfterCommand(root, ['--root', root, 'integrate', 'r-real'], { status: 'ok', ms: 1, printed: `${JSON.stringify({ id: 'r-real', status: 'integrated', files: ['a'] })}\n` });
  events = await readJournal(root);
  assert.ok(events.some(event => event.kind === 'integration' && event.run === 'r-real'));
});

test('hand-written handoffs are never lost: each one gets its own backup, and only the exact template or a generated file is replaced', async t => {
  const root = await project(t);
  const target = path.join(root, 'coordination/HANDOFF.md');
  await fs.writeFile(target, '# Handoff\n\nStatus: not started. Fill this after every dispatch.\n');
  await writeHandoffFile(root);
  await assert.rejects(fs.access(path.join(root, 'coordination/HANDOFF.previous.md')), 'the untouched template needs no backup');
  await fs.writeFile(target, 'first hand-written handoff\n');
  await writeHandoffFile(root);
  await fs.writeFile(target, 'second hand-written handoff, mentions Status: not started in passing\n');
  await writeHandoffFile(root);
  await fs.writeFile(target, 'third\n');
  await writeHandoffFile(root);
  assert.equal(await fs.readFile(path.join(root, 'coordination/HANDOFF.previous.md'), 'utf8'), 'first hand-written handoff\n');
  assert.match(await fs.readFile(path.join(root, 'coordination/HANDOFF.previous-2.md'), 'utf8'), /^second hand-written/);
  assert.equal(await fs.readFile(path.join(root, 'coordination/HANDOFF.previous-3.md'), 'utf8'), 'third\n');
  assert.match(await fs.readFile(target, 'utf8'), /^<!-- generated by swarm/);
});

test('a planted symlink can never make handoff, checkpoint or journal writes or deletes reach outside the project', async t => {
  const root = await project(t);
  const outside = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'swarm-p10b-outside-')));
  t.after(() => fs.rm(outside, { recursive: true, force: true }));
  await fs.writeFile(path.join(outside, 'precious.md'), 'keep');
  // HANDOFF.md as a symlink to a file outside
  await fs.rm(path.join(root, 'coordination/HANDOFF.md'), { force: true });
  await fs.symlink(path.join(outside, 'precious.md'), path.join(root, 'coordination/HANDOFF.md'));
  await assert.rejects(writeHandoffFile(root), /journal-path-unsafe/);
  assert.equal(await fs.readFile(path.join(outside, 'precious.md'), 'utf8'), 'keep');
  await fs.rm(path.join(root, 'coordination/HANDOFF.md'));
  // checkpoints folder as a symlink to a folder with other .md files
  for (let n = 0; n < 25; n += 1) await fs.writeFile(path.join(outside, `n${n}.md`), 'x');
  await fs.mkdir(path.join(root, '.swarm/project'), { recursive: true });
  await fs.symlink(outside, path.join(root, '.swarm/project/checkpoints'));
  await assert.rejects(runCheckpointCommand(root, ['--quiet']), /journal-path-unsafe/);
  assert.equal((await fs.readdir(outside)).filter(file => file.startsWith('n')).length, 25);
  // coordination itself as a symlink
  const linked = await project(t);
  await fs.rm(path.join(linked, 'coordination'), { recursive: true });
  await fs.symlink(outside, path.join(linked, 'coordination'));
  await assert.rejects(writeHandoffFile(linked), /journal-path-unsafe/);
});
