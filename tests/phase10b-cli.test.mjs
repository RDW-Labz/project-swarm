import { resolveDefaultRoot, projectRootFrom, findProjectRoot, journalCommandEvent, eventsFromResult, writeHandoffFile, runCheckpointCommand, pickArgument, journalAfterCommand } from '../tools/project-commands.mjs';
import { readJournal, appendEvent } from '../tools/journal.mjs';
import { worktreeDirty } from '../tools/goal.mjs';

const exec = promisify(execFile);
const swarm = path.join(path.dirname(fileURLToPath(import.meta.url)), '../tools/swarm.mjs');
const run = (root, args) => exec(process.execPath, [swarm, '--root', root, ...args], { env: { ...process.env, SWARM_CONFIG: process.env.SWARM_CONFIG, HOME: root } });
const fail = (root, args) => run(root, args).then(() => assert.fail('expected failure'), error => error);

async function project(t, { git = false } = {}) {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'swarm-p10b-')));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.writeFile(path.join(root, '.project-swarm.json'), JSON.stringify({ install: '/x', version: '1.0.0' }));
  await fs.mkdir(path.join(root, 'coordination'), { recursive: true });
  await fs.writeFile(path.join(root, 'coordination/TASK.md'), '# Task\n');
  if (git) {
    await exec('git', ['init', '-q', root]);
    await exec('git', ['-C', root, 'add', '-A']);
    await exec('git', ['-C', root, '-c', 'user.name=T', '-c', 'user.email=t@example.invalid', 'commit', '-qm', 'init']);
  }
  return root;
}

test('every command is journaled with a redacted argument list, and HANDOFF.md is regenerated', async t => {
  const root = await project(t);
  await run(root, ['note', 'decided to use sk-ant-abcdefghijklmnopqrstuvwxyz for nothing']);
  const events = await readJournal(root);
  const command = events.find(event => event.kind === 'command');
  assert.equal(command.cmd, 'note');
  assert.equal(command.status, 'ok');
  assert.ok(!JSON.stringify(events).includes('sk-ant-abcdefghijklmnop'));
  assert.ok(events.some(event => event.kind === 'note' && /decided to use/.test(event.text)));
  const handoff = await fs.readFile(path.join(root, 'coordination/HANDOFF.md'), 'utf8');
  assert.match(handoff, /^<!-- generated by swarm; do not edit/);
  assert.match(handoff, /Next 3 actions/);
});

test('a failing command is journaled as an error', async t => {
  const root = await project(t);
  const error = await fail(root, ['inspect', 'no-such-run']);
  assert.ok(error.code !== 0);
  const command = (await readJournal(root)).find(event => event.kind === 'command');
  assert.equal(command.cmd, 'inspect');
  assert.equal(command.status, 'error');
});

test('version, completion and help never create a journal', async t => {
  const root = await project(t);
  await run(root, ['completion', 'zsh']);
  await run(root, ['help']);
  await assert.rejects(fs.access(path.join(root, '.swarm/project/journal.ndjson')));
});

test('brief fits in 4 KB, names the next three actions, and --json is parseable', async t => {
  const root = await project(t);
  await appendEvent(root, { kind: 'goal', text: 'Ship the thing', doneWhen: 'tests pass' });
  const { stdout } = await run(root, ['brief']);
  assert.match(stdout, /^Project Swarm brief/);
  assert.match(stdout, /Ship the thing/);
  assert.ok(Buffer.byteLength(stdout) <= 4097);
  assert.match(stdout, /Next 3 actions/);
  const json = JSON.parse((await run(root, ['brief', '--json'])).stdout);
  assert.equal(json.next.length, 3);
  assert.ok(json.next.every(command => command.startsWith('swarm ')));
});

test('handoff prints a message for each agent and refuses an unknown one', async t => {
  const root = await project(t);
  for (const agent of ['codex', 'cursor', 'claude', 'gemini']) {
    const { stdout } = await run(root, ['handoff', '--to', agent]);
    assert.match(stdout, /orchestrator/i);
    assert.match(stdout, /Project Swarm brief/);
  }
  assert.equal((await fail(root, ['handoff', '--to', 'bogus'])).code, 1);
  assert.equal((await fail(root, ['handoff'])).code, 1);
});

test('checkpoint saves a snapshot, journals it, keeps the newest 20, and --quiet prints nothing', async t => {
  const root = await project(t);
  let clock = Date.parse('2026-10-15T00:00:00Z');
  for (let index = 0; index < 23; index += 1) await runCheckpointCommand(root, ['--quiet'], { now: () => (clock += 1000) });
  const files = await fs.readdir(path.join(root, '.swarm/project/checkpoints'));
  assert.equal(files.length, 20);
  assert.equal((await run(root, ['checkpoint', '--quiet'])).stdout, '');
  assert.match((await run(root, ['checkpoint'])).stdout, /checkpoint saved: \.swarm\/project\/checkpoints\//);
  assert.ok((await readJournal(root, { kinds: ['checkpoint'] })).length >= 23);
});

test('a hand-written HANDOFF.md is kept once as HANDOFF.previous.md before the generated one replaces it', async t => {
  const root = await project(t);
  await fs.writeFile(path.join(root, 'coordination/HANDOFF.md'), 'Hand-written notes that matter.\n');
  assert.equal((await writeHandoffFile(root)).written, true);
  assert.equal(await fs.readFile(path.join(root, 'coordination/HANDOFF.previous.md'), 'utf8'), 'Hand-written notes that matter.\n');
  assert.equal((await writeHandoffFile(root)).written, false);
  const noCoordination = await fs.mkdtemp(path.join(os.tmpdir(), 'swarm-p10b-none-'));
  t.after(() => fs.rm(noCoordination, { recursive: true, force: true }));
  assert.equal((await writeHandoffFile(noCoordination)).written, false);
});

